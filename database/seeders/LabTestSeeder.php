    {
        $tests = $this->getCatalogData();

        DB::transaction(function () use ($tests) {
            foreach ($tests as $test) {
                // Programmatic validation
                if (empty($test['name']) || empty($test['category'])) {
                    continue;
                }

                $attributes = [
                    'name' => trim($test['name']),
                    'category' => trim($test['category']),
                ];

                $values = [
                    'short_name' => isset($test['short_name']) && $test['short_name'] !== '' ? trim($test['short_name']) : null,
                    'loinc_code' => isset($test['loinc_code']) && $test['loinc_code'] !== '' ? trim($test['loinc_code']) : null,
                    'description' => isset($test['description']) && $test['description'] !== '' ? trim($test['description']) : null,
                    'specimen' => isset($test['specimen']) && $test['specimen'] !== '' ? trim($test['specimen']) : null,
